#!/usr/bin/env bash
set -euo pipefail

# Usage: ./scripts/create-release.sh <tag> [--prerelease] [--dry-run]
# Creates or updates a GitHub Release with consistent highlights and change lists.

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

PRERELEASE=false
DRY_RUN=false

if [[ "${1:-}" == "--" ]]; then
  shift
fi

TAG="${1:-}"
shift || true
while [[ $# -gt 0 ]]; do
  case "$1" in
    --prerelease)
      PRERELEASE=true
      shift
      ;;
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    *)
      echo -e "${RED}Unknown option: $1${NC}"
      exit 1
      ;;
  esac
done

if [[ -z "$TAG" || ! "$TAG" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]]; then
  echo -e "${RED}Usage: $0 <vMAJOR.MINOR.PATCH[-PRERELEASE]> [--prerelease] [--dry-run]${NC}"
  exit 1
fi

if [[ "$TAG" == *-* ]]; then
  PRERELEASE=true
fi

if [[ "$PRERELEASE" == true && "$TAG" != *-* ]]; then
  echo -e "${RED}Error: --prerelease requires a tag with a prerelease suffix.${NC}"
  exit 1
fi

if [[ "$PRERELEASE" == false && "$TAG" == *-* ]]; then
  echo -e "${RED}Error: prerelease tags must be created with --prerelease.${NC}"
  exit 1
fi

if ! command -v gh >/dev/null 2>&1; then
  echo -e "${RED}Error: GitHub CLI (gh) is required.${NC}"
  exit 1
fi

if [[ -z "${GH_TOKEN:-}" && -z "${GITHUB_TOKEN:-}" ]]; then
  echo -e "${RED}Error: GH_TOKEN or GITHUB_TOKEN is required.${NC}"
  exit 1
fi

REPOSITORY="${GITHUB_REPOSITORY:-}"
if [[ -z "$REPOSITORY" ]]; then
  REPOSITORY="$(git remote get-url origin | sed -E 's#.*github.com[:/]##; s#\.git$##')"
fi

if [[ -z "$REPOSITORY" || "$REPOSITORY" != */* ]]; then
  echo -e "${RED}Error: could not determine the GitHub repository.${NC}"
  exit 1
fi

VERSION="${TAG#v}"
TARGET_BRANCH="main"
[[ "$PRERELEASE" == true ]] && TARGET_BRANCH="dev"

if ! gh api "repos/$REPOSITORY/git/ref/tags/$TAG" --silent >/dev/null 2>&1; then
  echo -e "${RED}Error: tag $TAG does not exist on GitHub.${NC}"
  exit 1
fi

COMPARE_STATUS="$(gh api "repos/$REPOSITORY/compare/$TAG...$TARGET_BRANCH" --jq '.status')"
if [[ "$COMPARE_STATUS" != "ahead" && "$COMPARE_STATUS" != "identical" ]]; then
  echo -e "${RED}Error: $TAG is not contained in $TARGET_BRANCH (status: $COMPARE_STATUS).${NC}"
  exit 1
fi

PREVIOUS_TAG="$(
  gh api "repos/$REPOSITORY/tags" --paginate --jq '.[].name' |
    grep -E '^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$' |
    sort -V |
    awk -v current="$TAG" '
      $0 == current { found = 1; next }
      !found { previous = $0 }
      END { print previous }
    '
)"

COMPARE_URL="repos/$REPOSITORY/compare/$TAG"
if [[ -n "$PREVIOUS_TAG" ]]; then
  COMPARE_URL="repos/$REPOSITORY/compare/$PREVIOUS_TAG...$TAG"
fi

COMPARE_JSON="$(gh api "$COMPARE_URL")"
TEMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TEMP_DIR"' EXIT

HIGHLIGHTS_FILE="$TEMP_DIR/highlights"
BODY_FILE="$TEMP_DIR/body"
PRS_FILE="$TEMP_DIR/prs"

if [[ ! -f CHANGELOG.md ]]; then
  echo -e "${RED}Error: CHANGELOG.md is required to generate release highlights.${NC}"
  exit 1
fi

awk -v heading="## [$VERSION]" '
  index($0, heading) == 1 { found = 1; next }
  found && /^## / { exit }
  found && /^### Pending$/ { exit }
  found { print }
' CHANGELOG.md > "$HIGHLIGHTS_FILE"

if [[ ! -s "$HIGHLIGHTS_FILE" ]]; then
  echo -e "${RED}Error: CHANGELOG.md has no release section for $VERSION.${NC}"
  exit 1
fi

: > "$PRS_FILE"
while IFS= read -r commit_sha; do
  gh api "repos/$REPOSITORY/commits/$commit_sha/pulls" --jq \
    '.[] | select(.merged_at != null) | [.number, .title, .html_url] | @tsv' >> "$PRS_FILE"
done < <(printf '%s' "$COMPARE_JSON" | jq -r '.commits[].sha')

sort -t "$(printf '\t')" -k1,1n -u "$PRS_FILE" -o "$PRS_FILE"

{
  echo "## Highlights"
  cat "$HIGHLIGHTS_FILE"
  echo
  echo "## Changes"
  echo
  echo "### Pull requests"
  if [[ -s "$PRS_FILE" ]]; then
    while IFS=$'\t' read -r number title url; do
      printf -- '- [#%s](%s) %s\n' "$number" "$url" "$title"
    done < "$PRS_FILE"
  else
    echo "- No pull requests were associated with this release."
  fi
  echo
  echo "### Commits"
  printf '%s' "$COMPARE_JSON" | jq -r \
    '.commits[] | "- [`" + (.sha[0:7]) + "`](https://github.com/'"$REPOSITORY"'/commit/" + .sha + ") " + (.commit.message | split("\n")[0])'
  echo
  echo "<!-- Generated by scripts/create-release.sh. -->"
} > "$BODY_FILE"

RELEASE_TITLE="Kalenda $TAG"

if [[ "$DRY_RUN" == true ]]; then
  echo -e "${YELLOW}[dry-run] Release title: $RELEASE_TITLE${NC}"
  cat "$BODY_FILE"
  exit 0
fi

if gh release view "$TAG" --repo "$REPOSITORY" --json tagName >/dev/null 2>&1; then
  gh release edit "$TAG" \
    --repo "$REPOSITORY" \
    --title "$RELEASE_TITLE" \
    --notes-file "$BODY_FILE" \
    $([[ "$PRERELEASE" == true ]] && echo --prerelease || true)
else
  gh release create "$TAG" \
    --repo "$REPOSITORY" \
    --title "$RELEASE_TITLE" \
    --notes-file "$BODY_FILE" \
    $([[ "$PRERELEASE" == true ]] && echo --prerelease || true)
fi

echo -e "${GREEN}✓ Published $RELEASE_TITLE${NC}"
